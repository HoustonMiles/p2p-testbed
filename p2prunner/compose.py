"""
Writes the Docker Compose file for a testbed of N peers.

    uv run python -m p2prunner compose --peers 4            # print it
    uv run python -m p2prunner up --peers 4 --cgn b,d       # write .testbed/compose.yml and start it

The committed docker-compose.yml is this generator's output for two peers
that may both be put behind CGNAT (`compose --peers 2 --cgn a,b`); a test
fails if the two drift apart, so edit this file, not that one.

Each peer gets a CGN (and its carrier network) only when it may sit behind
one, which keeps large testbeds small. Run-time settings (NAT types,
upstream, link profiles) stay environment variables, as before.
"""

from __future__ import annotations

from p2prunner import topology
from p2prunner.topology import Peer

HEADER = """\
# =============================================================================
# P2P testbed topology. GENERATED by p2prunner/compose.py; edit that, not this.
#
#   [peer-a]--lan_a--[nat-a]--+------------------ wan ------------------+--[nat-b]--lan_b--[peer-b]
#                             |                                         |
#                             +--carrier_a--[cgn-a]--wan    wan--[cgn-b]--carrier_b--+
#
# Each peer is a household: a computer behind its home router, optionally
# behind its ISP's carrier-grade NAT. wan (198.18.0.0/15) is the simulated
# public internet, where the services (STUN, rendezvous; relay and attackers
# later) live. Addresses: see p2prunner/topology.py.
#
# A home router wired to both the wan and its carrier network uses the one
# its UPSTREAM setting picks and switches the other off:
#   UPSTREAM=wan   -> the home router has a public IP (normal home internet)
#   UPSTREAM=cgnat -> the home router sits behind the ISP's CGN (two NAT layers)
#
# Pick a configuration with environment variables (see .env.example), e.g.
#   NAT_A_TYPE=symmetric NET_PROFILE=coast docker compose up -d --build --wait
# Per-peer link settings (NET_PROFILE_A, UPLINK_MBIT_B, ...) override the
# global ones (NET_PROFILE, UPLINK_MBIT, DOWNLINK_MBIT).
# =============================================================================

# --- Shared settings (YAML anchors, merged into services below) ---
x-router: &router
  build: ./testbed/router
  image: p2p-testbed/router
  init: true                      # tini as PID 1, so containers stop instantly
  cap_add: [NET_ADMIN]            # needed for iptables, routes and tc
  sysctls:
    net.ipv4.ip_forward: 1        # act as a router
    net.ipv4.conf.all.rp_filter: 0      # don't drop packets on "unexpected" interfaces
    net.ipv4.conf.default.rp_filter: 0
    # How long an idle UDP mapping (pinhole) stays open. Real routers vary
    # (roughly 30-180 s); this matters for when old hop ports close.
    net.netfilter.nf_conntrack_udp_timeout: ${UDP_TIMEOUT:-30}
    net.netfilter.nf_conntrack_udp_timeout_stream: ${UDP_TIMEOUT_STREAM:-120}
  healthcheck:                    # healthy once configure-router.sh finishes
    test: ["CMD", "test", "-f", "/tmp/ready"]
    interval: 1s
    retries: 30

x-host: &host
  # Built from the repository root so the Go tools in p2p/ can be
  # compiled into the image (see testbed/host/Dockerfile and .dockerignore).
  build: { context: ., dockerfile: testbed/host/Dockerfile }
  image: p2p-testbed/host
  init: true
  cap_add: [NET_ADMIN]            # needed to replace the default route
  healthcheck:
    test: ["CMD", "test", "-f", "/tmp/ready"]
    interval: 1s
    retries: 30

services:
"""

SERVICES = f"""\
  # ---------------------------------------------------------------------------
  # WAN services
  # ---------------------------------------------------------------------------
  # stun: coturn in STUN-only mode. Answers "what is my public address?" on
  # UDP 3478 and supports the RFC 5780 NAT behaviour tests, which need a
  # second IP ({topology.STUN_ALT_IP}, added by start-stun.sh) and a second port (3479).
  stun:
    build: ./testbed/stun
    image: p2p-testbed/stun
    init: true
    cap_add: [NET_ADMIN]            # needed to add the second IP address
    environment:
      PRIMARY_IP: {topology.STUN_IP}
      ALT_IP: {topology.STUN_ALT_IP}
    networks:
      wan: {{ ipv4_address: {topology.STUN_IP} }}
    healthcheck:                    # healthy once it answers a real STUN request
      # timeout: the client can wait on RFC 5780 replies; cap each check.
      test: ["CMD", "timeout", "3", "turnutils_stunclient", "{topology.STUN_IP}"]
      interval: 1s
      timeout: 5s
      retries: 30

  # rendezvous: introduces the members of each room to each other
  # (p2p/cmd/rendezvous). It only sees each peer's public address and never
  # relays peer traffic. Uses the host image, which contains the binary.
  rendezvous:
    <<: *host
    networks:
      wan: {{ ipv4_address: {topology.RENDEZVOUS_IP} }}
    command: ["rendezvous", "-listen", ":7000"]

  # Reserved WAN addresses for later steps:
  #   {topology.RELAY_IP}  coturn relay
  #   {topology.STUN_ALT_IP}  STUN alternate IP (not visible to Docker, so keep it free)
  #   198.18.0.200+ attacker containers
"""

NETWORKS_HEADER = """\

# =============================================================================
# Networks. Fixed subnets so every address above is predictable.
#
# gateway_mode_ipv4 = nat-unprotected: since Docker 28, the host drops any
# packet addressed to a container's IP that arrives from a different Docker
# network. Our routers do exactly that on purpose (peer-a -> nat-a -> stun),
# so we turn that protection off for these networks. Isolation is enforced
# by our own NAT routers instead. Docker versions before 28 never had the
# protection and don't need this option.
#
# enable_ip_masquerade = false: Docker normally adds a host rule that
# masquerades each network's subnet when its traffic leaves through another
# bridge. Our routers forward exactly such traffic (a peer's public WAN
# address arriving on a LAN after a cone NAT lets it in), and the host rule
# would rewrite its source to the LAN bridge's gateway. The testbed never
# needs the host to NAT anything to the real internet.
# =============================================================================
x-net-opts: &net_opts
  com.docker.network.bridge.gateway_mode_ipv4: nat-unprotected
  com.docker.network.bridge.enable_ip_masquerade: "false"

networks:
"""


def render(n: int, cgn: set[str] = frozenset()) -> str:
    """The compose file for peers 1..n; cgn names the peers that get a CGN."""
    ps = topology.peers(n)
    unknown = set(cgn) - {p.name for p in ps}
    if unknown:
        raise ValueError(f"--cgn names peers that are not in the testbed: {sorted(unknown)}")
    parts = [HEADER]
    for p in ps:
        parts.append(peer_services(p, p.name in cgn))
    parts.append(SERVICES)
    parts.append(NETWORKS_HEADER)
    for p in ps:
        parts.append(peer_networks(p, p.name in cgn))
    parts.append(wan_network())
    return "".join(parts)


def peer_services(p: Peer, with_cgn: bool) -> str:
    title = f"Peer {p.name}" + (" (with a CGN it may sit behind)" if with_cgn else "")
    text = f"""\
  # ---------------------------------------------------------------------------
  # {title}
  # ---------------------------------------------------------------------------
  peer-{p.name}:
    <<: *host
    environment:
      GATEWAY: {p.router_lan_ip}                   # nat-{p.name}'s LAN address
    # Static Noise keys, made with: docker compose exec peer-{p.name} punch -genkey /keys/{p.name}
    volumes: ["./keys:/keys"]
    networks:
      lan_{p.name}: {{ ipv4_address: {p.peer_ip} }}
    depends_on:
      nat-{p.name}: {{ condition: service_healthy }}

{home_router(p, with_cgn)}"""
    return text + (cgn_router(p) if with_cgn else "") + "\n"


def home_router(p: Peer, with_cgn: bool) -> str:
    v = p.name.upper()
    carrier_env = f"""\
      CARRIER_IP: {p.router_carrier_ip}                # carrier IP when UPSTREAM=cgnat
      CGN_IP: {p.cgn_inside_ip}                     # cgn-{p.name}, next hop when UPSTREAM=cgnat
""" if with_cgn else ""
    carrier_net = f"      carrier_{p.name}: {{ ipv4_address: {p.router_carrier_ip} }}\n" if with_cgn else ""
    depends = f"    depends_on:\n      cgn-{p.name}: {{ condition: service_healthy }}\n" if with_cgn else ""
    return f"""\
  nat-{p.name}:
    <<: *router
    environment:
      ROLE: home
      NAT_TYPE: ${{NAT_{v}_TYPE:-port_restricted}}
      UPSTREAM: ${{NAT_{v}_UPSTREAM:-wan}}
      LAN_IP: {p.router_lan_ip}
      LAN_SUBNET: {p.lan_subnet}
      INSIDE_HOST: {p.peer_ip}                 # peer-{p.name}
      WAN_IP: {p.wan_ip}                    # public IP when UPSTREAM=wan
{carrier_env}{link_env(v)}      DEBUG: ${{DEBUG:-0}}
    networks:
      lan_{p.name}: {{ ipv4_address: {p.router_lan_ip} }}
{carrier_net}      wan: {{ ipv4_address: {p.wan_ip} }}
{depends}"""


def link_env(v: str) -> str:
    """This peer's access link: its own setting, else the global one."""
    lines = []
    for var, default in (("NET_PROFILE", "local"), ("UPLINK_MBIT", ""), ("DOWNLINK_MBIT", "")):
        lines.append(f"      {var}: ${{{var}_{v}:-}}\n")
        lines.append(f"      DEFAULT_{var}: ${{{var}:-{default}}}\n")
    return "".join(lines)


def cgn_router(p: Peer) -> str:
    return f"""
  cgn-{p.name}:
    <<: *router
    environment:
      ROLE: cgn
      NAT_TYPE: ${{CGN_{p.name.upper()}_TYPE:-port_restricted}}
      INSIDE_IP: {p.cgn_inside_ip}
      INSIDE_SUBNET: {p.carrier_subnet}
      INSIDE_HOST: {p.router_carrier_ip}                # nat-{p.name}'s carrier address
      OUTSIDE_IP: {p.cgn_wan_ip}                # peer {p.name}'s public IP when behind CGNAT
      DEBUG: ${{DEBUG:-0}}
    networks:
      carrier_{p.name}: {{ ipv4_address: {p.cgn_inside_ip} }}
      wan:       {{ ipv4_address: {p.cgn_wan_ip} }}
"""


def peer_networks(p: Peer, with_cgn: bool) -> str:
    text = f"""\
  lan_{p.name}:
    driver_opts: *net_opts
    ipam: {{ config: [ {{ subnet: {p.lan_subnet}, gateway: {p.lan_bridge} }} ] }}
"""
    if with_cgn:
        text += f"""\
  carrier_{p.name}:                                 # the ISP's network between home router and CGN
    driver_opts: *net_opts
    ipam: {{ config: [ {{ subnet: {p.carrier_subnet}, gateway: {p.carrier_bridge} }} ] }}
"""
    return text


def wan_network() -> str:
    return f"""\
  wan:                                       # the "public internet" (RFC 2544 benchmark range)
    driver_opts: *net_opts
    ipam: {{ config: [ {{ subnet: {topology.WAN_SUBNET}, gateway: {topology.WAN_GATEWAY} }} ] }}
"""


def default() -> str:
    """The committed docker-compose.yml: two peers, both with a CGN."""
    return render(2, {"a", "b"})
